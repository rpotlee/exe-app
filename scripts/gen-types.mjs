// Generates TypeScript types from the SQL migrations, so a screen cannot disagree with the schema (DEC-005).
// Usage: node scripts/gen-types.mjs        (writes src/db/types.ts)
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { freshDb } from '../supabase/tests/harness.mjs';

const TS = { uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', int4: 'number', int8: 'number', numeric: 'number', bool: 'boolean',
  timestamptz: 'string', timestamp: 'string', date: 'string', jsonb: 'Json', json: 'Json', bytea: 'string' };
const tsType = (udt) => udt.startsWith('_') ? `${TS[udt.slice(1)] ?? 'unknown'}[]` : (TS[udt] ?? 'unknown');

export async function generate() {
  const db = await freshDb();
  const cols = (await db.query(`
    select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, t.table_type
    from information_schema.columns c join information_schema.tables t using (table_schema, table_name)
    where c.table_schema = 'public' order by c.table_name, c.ordinal_position`)).rows;
  const tables = new Map();
  for (const c of cols) { if (!tables.has(c.table_name)) tables.set(c.table_name, { view: c.table_type === 'VIEW', cols: [] }); tables.get(c.table_name).cols.push(c); }
  let out = `// GENERATED by scripts/gen-types.mjs from supabase/migrations. Do not edit by hand; run \`npm run gen:types\`.\n`;
  out += `export type Json = string | number | boolean | null | { [key: string]: Json } | Json[];\n\nexport interface Database {\n  public: {\n    Tables: {\n`;
  const views = [];
  for (const [name, t] of tables) {
    if (t.view) { views.push([name, t]); continue; }
    const row = t.cols.map(c => `          ${c.column_name}: ${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''};`).join('\n');
    const ins = t.cols.map(c => `          ${c.column_name}${c.is_nullable === 'YES' || c.column_default !== null ? '?' : ''}: ${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''};`).join('\n');
    const upd = t.cols.map(c => `          ${c.column_name}?: ${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''};`).join('\n');
    out += `      ${name}: {\n        Row: {\n${row}\n        };\n        Insert: {\n${ins}\n        };\n        Update: {\n${upd}\n        };\n        Relationships: [];\n      };\n`;
  }
  out += `    };\n    Views: {\n`;
  for (const [name, t] of views) out += `      ${name}: {\n        Row: {\n${t.cols.map(c => `          ${c.column_name}: ${tsType(c.udt_name)} | null;`).join('\n')}\n        };\n        Relationships: [];\n      };\n`;
  out += `    };\n    Functions: {\n      exe_apply_writes: { Args: { p_writes: Json }; Returns: undefined };\n      exe_apply_writes_once: { Args: { p_key: string; p_writes: Json }; Returns: boolean };\n    };\n    Enums: { [_ in never]: never };\n    CompositeTypes: { [_ in never]: never };\n  };\n}\n\nexport type Tables<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Row'];\nexport type TablesInsert<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Insert'];\nexport type TablesUpdate<T extends keyof Database['public']['Tables']> = Database['public']['Tables'][T]['Update'];\n`;
  const names = [...tables].filter(([, t]) => !t.view);
  out += `\n/** Real column names per table, for code that must refuse anything unexpected (imports). */\nexport const COLUMNS = {\n${names.map(([n, t]) => `  ${n}: [${t.cols.map(c => `'${c.column_name}'`).join(', ')}],`).join('\n')}\n} as const;\nexport type TableName = keyof typeof COLUMNS;\n`;
  return out;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'db', 'types.ts');
  writeFileSync(target, await generate()); console.log('wrote', target);
}
